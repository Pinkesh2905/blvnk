#!/usr/bin/env python3
"""Turn dropped-in product photos into optimised web images + js/photos.js.

Put originals here (jpg / jpeg / png / webp):

    img/products/<product-slug>/<colour-index>-<shot>.<ext>
    e.g. img/products/void-runner/0-1.png   (colour 0, shot 1 = main image)
         img/products/void-runner/0-2.png   (colour 0, shot 2)
         img/products/void-runner/1-1.png   (colour 1, shot 1)

Then run:   python tools/build-photos.py      (needs Pillow: pip install pillow)

For every original it writes three WebP sizes (360 / 720 / 1200 px wide) to
    img/web/<slug>/<colour>-<shot>.<content-hash>-<width>.webp
The content hash is in the file name, so files can be cached forever and a changed photo
automatically gets a new URL. Stale files from older runs are removed. The site picks the right
size per screen with srcset. Colours with no photos keep the generated renders.

Shot order = gallery order: sneakers 1 side · 2 three-quarter front · 3 heel/back · 4 outsole
                            caps     1 three-quarter · 2 front · 3 side · 4 top/back
"""
import hashlib, json, re, sys
from pathlib import Path

try:
    from PIL import Image
except ImportError:
    sys.exit('Pillow is required: pip install pillow')

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / 'img' / 'products'
WEB = ROOT / 'img' / 'web'
EXT = {'.jpg', '.jpeg', '.png', '.webp'}
PAT = re.compile(r'^(\d+)-(\d+)$')
WIDTHS = (360, 720, 1200)
QUALITY = 80

photos, keep, count = {}, set(), 0
if SRC.exists():
    for d in sorted(p for p in SRC.iterdir() if p.is_dir()):
        for f in sorted(d.iterdir()):
            m = PAT.match(f.stem)
            if f.suffix.lower() not in EXT or not m:
                continue
            ci, shot = int(m[1]), int(m[2])
            digest = hashlib.md5(f.read_bytes()).hexdigest()[:8]
            stem = f'{ci}-{shot}.{digest}'
            out_dir = WEB / d.name
            out_dir.mkdir(parents=True, exist_ok=True)
            im = None
            for w in WIDTHS:
                out = out_dir / f'{stem}-{w}.webp'
                keep.add(out)
                if out.exists():
                    continue
                if im is None:
                    im = Image.open(f).convert('RGB')
                im2 = im.copy()
                if im2.width > w:
                    im2 = im2.resize((w, round(im2.height * w / im2.width)), Image.LANCZOS)
                im2.save(out, 'WEBP', quality=QUALITY, method=6)
            photos.setdefault(d.name, {}).setdefault(ci, {})[shot] = f'img/web/{d.name}/{stem}'
            count += 1

# remove web files that no longer belong to any original (old hashes, legacy jpgs)
if WEB.exists():
    for f in WEB.rglob('*'):
        if f.is_file() and f not in keep:
            f.unlink()
    for d in sorted(WEB.rglob('*'), reverse=True):
        if d.is_dir() and not any(d.iterdir()):
            d.rmdir()

final = {slug: {ci: [shots[k] for k in sorted(shots)] for ci, shots in cols.items()} for slug, cols in photos.items()}
js = ('/* Generated by tools/build-photos.py — do not edit by hand.\n'
      '   Each entry is a path stem; the site appends -360 / -720 / -1200 + .webp. */\n'
      '(function () {\n  var PHOTOS = ' + json.dumps(final, indent=2) + ';\n'
      '  (window.BLVNK_PRODUCTS || []).forEach(function (p) { if (PHOTOS[p.slug]) p.photos = PHOTOS[p.slug]; });\n})();\n')
(ROOT / 'js' / 'photos.js').write_text(js, encoding='utf-8')
total = sum(f.stat().st_size for f in keep) / 1048576
print(f'{count} photo(s) across {len(final)} product(s) -> js/photos.js, {len(keep)} webp files ({total:.1f} MB total)')
