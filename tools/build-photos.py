#!/usr/bin/env python3
"""Turn dropped-in product photos into js/photos.js.

Put originals here (any of jpg / jpeg / png / webp):

    img/products/<product-slug>/<colour-index>-<shot>.<ext>
    e.g. img/products/void-runner/0-1.png   (colour 0, shot 1 = hero)
         img/products/void-runner/0-2.png   (colour 0, shot 2)
         img/products/void-runner/1-1.png   (colour 1, shot 1)

Then run:   python tools/build-photos.py

If Pillow is installed, web-sized JPEGs (1200px, quality 86) are written to img/web/ and used by the site;
otherwise the originals are used as they are. Colours with no photos keep the generated renders.
Shot order = gallery order: sneakers  1 side · 2 three-quarter front · 3 heel/back · 4 outsole
                              caps     1 front · 2 side · 3 three-quarter · 4 top/back
"""
import json, re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / 'img' / 'products'
WEB = ROOT / 'img' / 'web'
EXT = {'.jpg', '.jpeg', '.png', '.webp'}
PAT = re.compile(r'^(\d+)-(\d+)$')

try:
    from PIL import Image
except ImportError:
    Image = None

photos, count = {}, 0
if SRC.exists():
    for d in sorted(p for p in SRC.iterdir() if p.is_dir()):
        for f in sorted(d.iterdir()):
            m = PAT.match(f.stem)
            if f.suffix.lower() not in EXT or not m:
                continue
            ci, shot = int(m[1]), int(m[2])
            url = f.relative_to(ROOT).as_posix()
            if Image:
                out = WEB / d.name / f'{ci}-{shot}.jpg'
                out.parent.mkdir(parents=True, exist_ok=True)
                im = Image.open(f).convert('RGB')
                im.thumbnail((1200, 1200), Image.LANCZOS)
                im.save(out, 'JPEG', quality=86, optimize=True, progressive=True)
                url = out.relative_to(ROOT).as_posix()
            photos.setdefault(d.name, {}).setdefault(ci, {})[shot] = url
            count += 1

# shots must be contiguous from 1; list order = gallery order
final = {}
for slug, cols in photos.items():
    for ci, shots in cols.items():
        ordered = [shots[k] for k in sorted(shots)]
        final.setdefault(slug, {})[ci] = ordered

js = ('/* Generated by tools/build-photos.py — do not edit by hand. */\n'
      '(function () {\n  var PHOTOS = ' + json.dumps(final, indent=2) + ';\n'
      '  (window.BLVNK_PRODUCTS || []).forEach(function (p) { if (PHOTOS[p.slug]) p.photos = PHOTOS[p.slug]; });\n})();\n')
(ROOT / 'js' / 'photos.js').write_text(js, encoding='utf-8')
print(f'{count} photo(s) across {len(final)} product(s) -> js/photos.js' + ('' if Image else '  (Pillow not found: using originals)'))
